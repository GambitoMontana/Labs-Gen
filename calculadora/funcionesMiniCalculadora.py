def suma(n1, n2):
    return n1 + n2

def resta(n1, n2):
    return n1 - n2

def mult(n1, n2):
    return n1 * n2

def div(n1, n2):
    if n2 == 0:
        return "La division entre cero no se puede..."
    return n1 / n2

def mod(n1, n2):
    return n1 % n2

def poW(n1, n2):
    return n1 ** n2

def sum3(n1, n2, n3):
    return n1 + n2 + n3